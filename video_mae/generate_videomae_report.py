# VIDEO
# ============================================================

def read_video(video_path):

    cap = cv2.VideoCapture(
        str(video_path)
    )

    if not cap.isOpened():
        raise RuntimeError(
            f"Could not open video: {video_path}"
        )

    source_fps = cap.get(
        cv2.CAP_PROP_FPS
    )

    frame_count = int(
        cap.get(cv2.CAP_PROP_FRAME_COUNT)
    )

    if source_fps <= 0:
        raise RuntimeError(
            f"Invalid FPS for {video_path}"
        )

    duration = frame_count / source_fps

    print(
        f"  FPS={source_fps:.3f}, "
        f"frames={frame_count}, "
        f"duration={duration:.3f}s"
    )

    frames = []

    while True:
        ret, frame = cap.read()

        if not ret:
            break

        frames.append(frame)

    cap.release()

    return frames, source_fps, duration


def sample_window(
    frames,
    source_fps,
    start_sec,
    window_len,
    num_frames
):

    times = np.linspace(
        start_sec,
        start_sec + window_len,
        num_frames,
        endpoint=False
    )

    sampled = []

    for t in times:

        frame_idx = int(
            round(t * source_fps)
        )

        frame_idx = max(
            0,
            min(
                frame_idx,
                len(frames) - 1
            )
        )

        frame = cv2.cvtColor(
            frames[frame_idx],
            cv2.COLOR_BGR2RGB
        )

        sampled.append(frame)

    return sampled


@torch.no_grad()
def predict(
    model,
    processor,
    device,
    frames
):

    inputs = processor(
        list(frames),
        return_tensors="pt"
    )

    inputs = {
        k: v.to(device)
        for k, v in inputs.items()
    }

    outputs = model(**inputs)

    probabilities = torch.softmax(
        outputs.logits,
        dim=-1
    )[0]

    pred_idx = int(
        torch.argmax(probabilities)
    )

    confidence = float(
        probabilities[pred_idx]
    )

    return (
        probabilities.cpu().numpy(),
        pred_idx,
        confidence
    )


