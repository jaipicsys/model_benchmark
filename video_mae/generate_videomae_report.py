# READ JUMBLED TIMELINE
# ============================================================

def read_timeline(timeline_file):
    """
    Reads timeline produced by the jumbled video generator.

    Example:
        1   step8       source.mkv   00:00:00.000  00:00:04.500
        2   step2       source.mkv   00:00:04.500  00:00:09.200
    """

    timeline = []

    pattern = re.compile(
        r"^\s*(\d+)\s+"
        r"(\S+)\s+"
        r"(\S+)\s+"
        r"(\d+:\d+:\d+\.\d+)\s+"
        r"(\d+:\d+:\d+\.\d+)"
    )

    with open(timeline_file, "r") as f:
        for line in f:
            match = pattern.match(line)

            if not match:
                continue

            index = int(match.group(1))
            step = match.group(2)
            source = match.group(3)
            start = parse_timestamp(match.group(4))
            end = parse_timestamp(match.group(5))

            timeline.append({
                "index": index,
                "step": step,
                "source": source,
                "start": start,
                "end": end,
                "duration": end - start
            })

    if not timeline:
        raise RuntimeError(
            f"No timeline entries found in {timeline_file}"
        )

    return timeline


# ============================================================
# CLASS NAME NORMALIZATION
# ============================================================

def canonical_class_name(label):
    """
    Converts equivalent class naming variants to one canonical name
    before comparing expected vs detected.

    Examples treated as the SAME class:
        step8
        start_step8
        START_STEP8
        start_Step_8
        step_8

    become:
        step8

    IMPORTANT:
        stop_step1 remains stop_step1.
        We only remove the harmless "start_" prefix.
    """

    if label is None:
        return ""

    label = str(label).strip().lower()

    # Normalize spaces / hyphens to underscores.
    label = re.sub(r"[\s\-]+", "_", label)

    # Remove leading start_ only.
    # DO NOT remove stop_, because stop_step1 is a
    # genuinely different class from step1.
    if label.startswith("start_"):
        label = label[len("start_"):]

    # Normalize things like step_8 -> step8.
    label = re.sub(
        r"^step_([0-9]+(?:\.[0-9]+)?)$",
        r"step\1",
        label
    )

    return label


def classes_match(expected, detected):
    """
    Returns True when expected and detected represent the same
    logical class after normalization.
    """

    return (
        canonical_class_name(expected)
        == canonical_class_name(detected)
    )


def canonical_display_name(label):
    """
    Display-friendly canonical class name.
    """

    return canonical_class_name(label)


def expected_step_at(t, timeline):
    """
    Returns the ground-truth step containing timestamp t.

    Returns:
        step
        is_boundary
    """

    for item in timeline:
        if item["start"] <= t < item["end"]:
            return item["step"], False

    # Timestamp can be close to a boundary or exactly at final end.
    for item in timeline:
        boundary_distance = min(
            abs(t - item["start"]),
            abs(t - item["end"])
        )

        if boundary_distance <= 0.001:
            return item["step"], True

    return "UNKNOWN", True


def overlapping_steps(start, end, timeline):
    """
    Returns all ground-truth steps touched by the window.
    """

    overlaps = []

    for item in timeline:
        overlap_start = max(start, item["start"])
        overlap_end = min(end, item["end"])

        overlap = max(
            0.0,
            overlap_end - overlap_start
        )

        if overlap > 0:
            overlaps.append(
                (item["step"], overlap)
            )

    return overlaps


def dominant_step(start, end, timeline):
    """
    Ground-truth class occupying the largest part of the
    VideoMAE window.
    """

    overlaps = overlapping_steps(
        start,
        end,
        timeline
    )

    if not overlaps:
        return "UNKNOWN", 0.0

    overlaps.sort(
        key=lambda x: x[1],
        reverse=True
    )

    step, duration = overlaps[0]

    window_duration = end - start

    percentage = (
        duration / window_duration * 100.0
        if window_duration > 0
        else 0
    )

    return step, percentage


