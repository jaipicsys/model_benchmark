#!/usr/bin/env python3

"""
VideoMAE Jumbled-Video Comparison Report

This script combines:
1. The jumbled-video timeline generated by the jumbled video script.
2. Raw sliding-window VideoMAE predictions.

For every VideoMAE window it determines:
    - timestamp
    - expected/ground-truth step at that timestamp
    - canonical expected class
    - detected step
    - canonical detected class
    - detected confidence
    - Correct / Wrong / Boundary
    - probability of the expected class
    - probability of the detected class

It also creates an Excel workbook with:
    - Window Results
    - Summary
    - Ground Truth Timeline
    - Per-Class Summary

Usage example:

python3 generate_videomae_report.py \
    --videomae_dir runs/roi_v4/videomae_finetuned/best_model \
    --jumbled_dir jumbled_tests \
    --output videomae_jumbled_report.xlsx \
    --window_len 2.0 \
    --stride 1.0 \
    --fps 15 \
    --num_frames 16

The script expects:
    jumbled_tests/
        jumbled_01.mkv
        jumbled_01_timeline.txt
        jumbled_02.mkv
        jumbled_02_timeline.txt
        ...

The timeline format is the format produced by the supplied jumbling script.
"""

