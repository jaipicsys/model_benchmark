# PROCESS ONE VIDEO
# ============================================================

def process_video(
    video_path,
    timeline_file,
    model,
    processor,
    device,
    args
):

    print("\n" + "=" * 90)
    print(f"Processing: {video_path.name}")
    print("=" * 90)

    timeline = read_timeline(
        timeline_file
    )

    print("\nGround-truth timeline:")

    for item in timeline:
        print(
            f"  {item['step']:<15} "
            f"{format_timestamp(item['start'])} -> "
            f"{format_timestamp(item['end'])}"
        )

    frames, source_fps, duration = read_video(
        video_path
    )

    id2label = model.config.id2label

    results = []

    start_sec = 0.0
    window_index = 0

    while start_sec + args.window_len <= duration:

        end_sec = (
            start_sec +
            args.window_len
        )

        frames_window = sample_window(
            frames,
            source_fps,
            start_sec,
            args.window_len,
            args.num_frames
        )

        probabilities, pred_idx, confidence = predict(
            model,
            processor,
            device,
            frames_window
        )

        detected = id2label.get(
            pred_idx,
            str(pred_idx)
        )

        # ---------------------------------------------
        # Ground truth at window midpoint
        # ---------------------------------------------

        midpoint = (
            start_sec + end_sec
        ) / 2.0

        expected_mid, midpoint_boundary = (
            expected_step_at(
                midpoint,
                timeline
            )
        )

        # ---------------------------------------------
        # Dominant ground truth inside full window
        # ---------------------------------------------

        expected_dominant, dominant_pct = (
            dominant_step(
                start_sec,
                end_sec,
                timeline
            )
        )

        # ---------------------------------------------
        # Which steps does this window touch?
        # ---------------------------------------------

        overlaps = overlapping_steps(
            start_sec,
            end_sec,
            timeline
        )

        overlap_text = ", ".join(
            f"{step} ({duration:.2f}s)"
            for step, duration in overlaps
        )

        # ---------------------------------------------
        # Probability for expected classes
        # ---------------------------------------------

        expected_mid_prob = None

        if expected_mid in id2label.values():

            expected_mid_idx = next(
                (
                    i for i, label
                    in id2label.items()
                    if label == expected_mid
                ),
                None
            )

            if expected_mid_idx is not None:
                expected_mid_prob = float(
                    probabilities[
                        expected_mid_idx
                    ]
                )

        expected_dom_prob = None

        if expected_dominant in id2label.values():

            expected_dom_idx = next(
                (
                    i for i, label
                    in id2label.items()
                    if label == expected_dominant
                ),
                None
            )

            if expected_dom_idx is not None:
                expected_dom_prob = float(
                    probabilities[
                        expected_dom_idx
                    ]
                )

        # ---------------------------------------------
        # Status
        # ---------------------------------------------

        # IMPORTANT:
        # Compare canonicalized names rather than raw strings.
        #
        # Example:
        #   expected = step8
        #   detected = start_step8
        #
        # These are treated as the SAME class.
        #
        # But:
        #   expected = step1
        #   detected = stop_step1
        #
        # remain DIFFERENT classes.

        midpoint_match = classes_match(
            expected_mid,
            detected
        )

        dominant_match_bool = classes_match(
            expected_dominant,
            detected
        )

        if midpoint_boundary:
            status = "BOUNDARY"

        elif midpoint_match:
            status = "CORRECT"

        else:
            status = "WRONG"

        # Also determine whether prediction matches
        # dominant class of the window.
        if dominant_match_bool:
            dominant_match = "YES"
        else:
            dominant_match = "NO"

        # Low confidence marker
        if confidence < args.confidence_threshold:
            threshold_status = "BELOW_THRESHOLD"
        else:
            threshold_status = "ABOVE_THRESHOLD"

        row = {
            "video": video_path.name,
            "window": window_index,
            "start_sec": start_sec,
            "end_sec": end_sec,
            "start": format_timestamp(start_sec),
            "end": format_timestamp(end_sec),
            "midpoint": format_timestamp(midpoint),

            "expected_midpoint": expected_mid,
            "expected_midpoint_canonical":
                canonical_class_name(expected_mid),

            "expected_dominant": expected_dominant,
            "expected_dominant_canonical":
                canonical_class_name(expected_dominant),

            "dominant_coverage_pct": dominant_pct,

            "detected": detected,
            "detected_canonical":
                canonical_class_name(detected),

            "confidence": confidence,

            "expected_mid_probability":
                expected_mid_prob,

            "expected_dominant_probability":
                expected_dom_prob,

            "status": status,
            "dominant_match": dominant_match,
            "threshold_status":
                threshold_status,

            "overlapping_steps":
                overlap_text
        }

        for i, probability in enumerate(
            probabilities
        ):
            label = id2label.get(
                i,
                str(i)
            )

            row[
                f"prob_{label}"
            ] = float(probability)

        results.append(row)

        print(
            f"[{window_index:04d}] "
            f"{format_timestamp(start_sec)} -> "
            f"{format_timestamp(end_sec)} | "
            f"GT={expected_mid:<15} | "
            f"DET={detected:<15} | "
            f"CONF={confidence:.3f} | "
            f"{status}"
        )

        window_index += 1
        start_sec += args.stride

    return results, timeline


