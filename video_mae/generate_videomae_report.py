# ============================================================

def main():

    args = parse_args()

    jumbled_dir = Path(
        args.jumbled_dir
    )

    if not jumbled_dir.exists():
        raise SystemExit(
            f"Directory not found: {jumbled_dir}"
        )

    model, processor, device = load_model(
        args.videomae_dir
    )

    video_files = sorted(
        jumbled_dir.glob(
            "jumbled_*.mkv"
        )
    )

    if not video_files:
        raise SystemExit(
            f"No jumbled_*.mkv videos found in "
            f"{jumbled_dir}"
        )

    all_results = []
    all_timelines = {}

    class_names = [
        model.config.id2label.get(
            i,
            str(i)
        )
        for i in range(
            model.config.num_labels
        )
    ]

    print(
        f"\nFound {len(video_files)} "
        f"jumbled videos."
    )

    for video_path in video_files:

        timeline_file = (
            video_path.parent /
            f"{video_path.stem}_timeline.txt"
        )

        if not timeline_file.exists():

            print(
                f"\nWARNING: Missing timeline:"
                f"\n  {timeline_file}"
            )

            continue

        results, timeline = process_video(
            video_path,
            timeline_file,
            model,
            processor,
            device,
            args
        )

        all_results.extend(
            results
        )

        all_timelines[
            video_path.name
        ] = timeline

    if not all_results:
        raise SystemExit(
            "No results generated."
        )

    create_report(
        all_results,
        all_timelines,
        args.output,
        class_names
    )

    print("\n" + "=" * 90)
    print("REPORT COMPLETE")
    print("=" * 90)
    print(
        f"Excel report: {args.output}"
    )
    print(
        f"Videos processed: "
        f"{len(all_timelines)}"
    )
    print(
        f"Windows evaluated: "
        f"{len(all_results)}"
    )
    print("=" * 90)


if __name__ == "__main__":
    main()

