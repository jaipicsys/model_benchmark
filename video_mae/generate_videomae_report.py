# TIME HELPERS
# ============================================================

def parse_timestamp(value):
    """
    Parses HH:MM:SS.mmm or MM:SS.mmm.
    """
    value = value.strip()

    parts = value.split(":")

    if len(parts) == 3:
        h = float(parts[0])
        m = float(parts[1])
        s = float(parts[2])
        return h * 3600 + m * 60 + s

    if len(parts) == 2:
        m = float(parts[0])
        s = float(parts[1])
        return m * 60 + s

    return float(value)


def format_timestamp(seconds):
    hours = int(seconds // 3600)
    minutes = int((seconds % 3600) // 60)
    secs = seconds % 60
    return f"{hours:02d}:{minutes:02d}:{secs:06.3f}"


