def style_sheet(ws):

    header_fill = PatternFill(
        "solid",
        fgColor="1F4E78"
    )

    header_font = Font(
        color="FFFFFF",
        bold=True
    )

    thin = Side(
        style="thin",
        color="D9E1F2"
    )

    for cell in ws[1]:

        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(
            horizontal="center",
            vertical="center"
        )

        cell.border = Border(
            bottom=thin
        )

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions

    for column_cells in ws.columns:

        max_length = 0
        column_letter = get_column_letter(
            column_cells[0].column
        )

        for cell in column_cells:

            value = str(
                cell.value
                if cell.value is not None
                else ""
            )

            max_length = max(
                max_length,
                len(value)
            )

        ws.column_dimensions[
            column_letter
        ].width = min(
            max(max_length + 2, 10),
            40
        )


def color_results(ws):

    correct_fill = PatternFill(
        "solid",
        fgColor="C6EFCE"
    )

    wrong_fill = PatternFill(
        "solid",
        fgColor="FFC7CE"
    )

    boundary_fill = PatternFill(
        "solid",
        fgColor="FFEB9C"
    )

    header = {
        cell.value: cell.column
        for cell in ws[1]
    }

    status_col = header.get(
        "Status"
    )

    if not status_col:
        return

    for row in range(
        2,
        ws.max_row + 1
    ):

        cell = ws.cell(
            row,
            status_col
        )

        if cell.value == "CORRECT":
            cell.fill = correct_fill

        elif cell.value == "WRONG":
            cell.fill = wrong_fill

        elif cell.value == "BOUNDARY":
            cell.fill = boundary_fill


